KS.units = {
  kg: { en: 'kg', hi: 'किलो' },
  g: { en: 'g', hi: 'ग्राम' },
  L: { en: 'L', hi: 'लीटर' },
  ml: { en: 'ml', hi: 'मि.ली.' },
  pc: { en: 'pc', hi: 'नग' },
  bunch: { en: 'bunch', hi: 'गड्डी' },
};

KS.lang = (function () {
  try { return localStorage.getItem('kitchen-saathi:lang') === 'hi' ? 'hi' : 'en'; } catch (e) { return 'en'; }
})();

KS.setLang = function (lang) {
  KS.lang = lang;
  try { localStorage.setItem('kitchen-saathi:lang', lang); } catch (e) { /* storage blocked */ }
};

KS.t = function (key, vars) {
  const table = KS.strings[KS.lang] || KS.strings.en;
  let s = table[key] != null ? table[key] : KS.strings.en[key] != null ? KS.strings.en[key] : key;
  if (vars) for (const k in vars) s = s.split('{' + k + '}').join(vars[k]);
  return s;
};

KS.unitLabel = function (u) {
  return (KS.units[u] && KS.units[u][KS.lang]) || u;
};

/* Pick the right-language name off any {en, hi} object. */
KS.nm = function (obj) {
  if (!obj) return '';
  return obj[KS.lang] || obj.en || '';
};
